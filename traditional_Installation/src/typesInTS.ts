// ----------------type inference----------------------
// TypeScript automatically guesses the type of a variable.
// You don’t need to write the type.
let age = 20;      // TypeScript infers type as number
let name = "Pooja"; // inferred as string



// ------------------------- Type annotation---------------------
// Type annotation means we explicitly define the data type.
let age1: number = 20;
let name1: string = "Pooja";
